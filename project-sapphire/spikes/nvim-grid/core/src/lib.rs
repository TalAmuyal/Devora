//! Spike 4 (#208): the core's side of the embedded Neovim (D9). The core owns the spawn spec, the config seeding (D14)
//! and the drafts; the RPC client and the grid live in Swift. Every export is fallible (spike 2 finding).

use std::fs;
use std::io::Write;
use std::path::{Path, PathBuf};
use std::sync::Mutex;

uniffi::setup_scaffolding!();

#[derive(Debug, thiserror::Error, uniffi::Error)]
pub enum CoreError {
    #[error("nvim not found on PATH")]
    NvimNotFound,
    #[error("I/O error at {path}: {message}")]
    Io { path: String, message: String },
    #[error("corrupt draft {id}: {message}")]
    CorruptDraft { id: String, message: String },
}

fn io_err(path: &Path) -> impl FnOnce(std::io::Error) -> CoreError + '_ {
    move |e| CoreError::Io { path: path.display().to_string(), message: e.to_string() }
}

#[derive(uniffi::Record, Debug, Clone)]
pub struct EnvVar {
    pub key: String,
    pub value: String,
}

#[derive(uniffi::Record, Debug, Clone)]
pub struct NvimSpawnSpec {
    pub program: String,
    pub args: Vec<String>,
    /// Added to (or overriding) the host's environment.
    pub env: Vec<EnvVar>,
    /// Removed from the host's environment.
    pub env_remove: Vec<String>,
}

/// `init` is the Devora-owned wrapper from `write_nvim_init`; `host_plugin` is a Lua file loaded before it
/// (navigation handoff, draft hooks, readiness).
#[uniffi::export]
pub fn nvim_spawn_spec(init: String, host_plugin: String, search_path: String) -> Result<NvimSpawnSpec, CoreError> {
    let program = std::env::split_paths(&search_path)
        .map(|dir| dir.join("nvim"))
        .find(|p| p.is_file())
        .ok_or(CoreError::NvimNotFound)?;
    Ok(NvimSpawnSpec {
        program: program.display().to_string(),
        args: vec![
            "--embed".into(),
            // nomore: a `-- More --` pager prompt blocks every RPC request, and if the host quits during one,
            // Neovim's exit path waits for a key forever and ignores SIGTERM.
            "--cmd".into(),
            "let g:devora_embedded = 1 | set nomore".into(),
            "--cmd".into(),
            format!("luafile {host_plugin}"),
            // Its own entry point rather than NVIM_APPNAME: the user's data, state and cache dirs (plugin manager,
            // tree-sitter parsers, shada, spell) stay shared.
            "-u".into(),
            init,
        ],
        env: vec![
            // The embedded editor is not inside tmux; don't let the config think it is.
            EnvVar { key: "TMUX".into(), value: String::new() },
        ],
        // Inherited from a terminal inside Neovim, $NVIM makes flatten.nvim-style plugins hand the buffer to that
        // parent Neovim and quit.
        env_remove: vec!["NVIM".into(), "NVIM_LISTEN_ADDRESS".into()],
    })
}

#[derive(uniffi::Record, Debug)]
pub struct NvimInit {
    pub path: String,
    pub user_init: String,
}

/// Writes `<dir>/init.lua`, a Devora-owned wrapper that sources the user's own config in place (D14). Copying the
/// config does not work: configs resolve their own path (`resolve($MYVIMRC)`), and with `NVIM_APPNAME` the plugin
/// manager, parsers and spell files (all under `stdpath("data")`) disappear. Never writes to the user's dirs.
#[uniffi::export]
pub fn write_nvim_init(dir: String, user_config_dir: String) -> Result<NvimInit, CoreError> {
    let user_config = PathBuf::from(&user_config_dir);
    let user_init = ["init.lua", "init.vim"]
        .iter()
        .map(|name| user_config.join(name))
        .find(|p| p.exists())
        .map(|p| fs::canonicalize(&p).unwrap_or(p));
    let dir = PathBuf::from(dir);
    fs::create_dir_all(&dir).map_err(io_err(&dir))?;
    let path = dir.join("init.lua");
    let source = match &user_init {
        Some(p) => format!("vim.env.MYVIMRC = {p:?}\nvim.cmd.source(vim.env.MYVIMRC)"),
        None => "-- no user config found".to_string(),
    };
    let wrapper = format!(
        r#"-- Generated by Devora for the embedded prompt editor; rewritten on every launch, so don't edit it.
-- Check `vim.g.devora_embedded` in your own config to skip terminal-only setup.
{source}

-- Plugins that fight an embedded editor. Each is optional, so a missing plugin is fine.
pcall(function() require("auto-session.config").enabled = false end) -- would replace the prompt buffer with a session
"#
    );
    fs::write(&path, wrapper).map_err(io_err(&path))?;
    Ok(NvimInit {
        path: path.display().to_string(),
        user_init: user_init.map(|p| p.display().to_string()).unwrap_or_default(),
    })
}

#[derive(uniffi::Record, Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize)]
pub struct Draft {
    pub id: String,
    pub lines: Vec<String>,
    /// 1-based row and 0-based byte column, as `nvim_win_get_cursor` reports them.
    pub cursor_row: u32,
    pub cursor_col: u32,
    pub changedtick: u64,
}

/// Stand-in for `devora-state`'s draft table: one JSON file per draft, replaced atomically.
#[derive(uniffi::Object)]
pub struct DraftStore {
    dir: PathBuf,
    write_lock: Mutex<()>,
}

#[uniffi::export]
impl DraftStore {
    #[uniffi::constructor]
    pub fn new(dir: String) -> Result<std::sync::Arc<Self>, CoreError> {
        let dir = PathBuf::from(dir);
        fs::create_dir_all(&dir).map_err(io_err(&dir))?;
        Ok(std::sync::Arc::new(Self { dir, write_lock: Mutex::new(()) }))
    }

    pub fn save(&self, draft: Draft) -> Result<(), CoreError> {
        let _guard = self.write_lock.lock().unwrap();
        let path = self.dir.join(format!("{}.json", draft.id));
        let tmp = path.with_extension("json.tmp");
        let json = serde_json::to_vec(&draft).expect("Draft serializes");
        let mut file = fs::File::create(&tmp).map_err(io_err(&tmp))?;
        file.write_all(&json).map_err(io_err(&tmp))?;
        file.sync_all().map_err(io_err(&tmp))?;
        fs::rename(&tmp, &path).map_err(io_err(&path))?;
        Ok(())
    }

    pub fn load(&self, id: String) -> Result<Option<Draft>, CoreError> {
        let path = self.dir.join(format!("{id}.json"));
        match fs::read(&path) {
            Ok(bytes) => serde_json::from_slice(&bytes)
                .map(Some)
                .map_err(|e| CoreError::CorruptDraft { id, message: e.to_string() }),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
            Err(e) => Err(io_err(&path)(e)),
        }
    }

    /// Where Neovim keeps this draft's undo history (`:wundo` / `:rundo`).
    pub fn undo_file(&self, id: String) -> Result<String, CoreError> {
        Ok(self.dir.join(format!("{id}.undo")).display().to_string())
    }
}
